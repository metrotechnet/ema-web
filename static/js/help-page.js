function getNormalizedSearchParams() {
    const rawSearch = String(window.location.search || '').replace(/&amp;/g, '&');
    return new URLSearchParams(rawSearch);
}

function getPreferredLanguage() {
    const fromBoot = String(window.EMA_HELP_LANG || '').trim().toLowerCase();
    if (['fr', 'en', 'es'].includes(fromBoot)) {
        return fromBoot;
    }

    const preferred = String(
        getNormalizedSearchParams().get('lang') || localStorage.getItem('preferredLanguage') || navigator.language || 'fr'
    )
        .split('-')[0]
        .toLowerCase();

    return ['fr', 'en', 'es'].includes(preferred) ? preferred : 'fr';
}

function getValueByPath(obj, path) {
    return String(path || '')
        .split('.')
        .reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
}

function applyHelpLocale(language) {
    const locale = HELP_I18N[language] || HELP_I18N.fr;

    document.querySelectorAll('[data-help-i18n]').forEach((node) => {
        const key = node.getAttribute('data-help-i18n');
        const value = getValueByPath(locale, key);
        if (value !== undefined) {
            node.textContent = value;
        }
    });

    document.querySelectorAll('[data-help-i18n-content]').forEach((node) => {
        const key = node.getAttribute('data-help-i18n-content');
        const value = getValueByPath(locale, key);
        if (value !== undefined) {
            node.setAttribute('content', value);
        }
    });

    document.querySelectorAll('[data-help-i18n-aria-label]').forEach((node) => {
        const key = node.getAttribute('data-help-i18n-aria-label');
        const value = getValueByPath(locale, key);
        if (value !== undefined) {
            node.setAttribute('aria-label', value);
        }
    });

    document.querySelectorAll('[data-help-i18n-alt]').forEach((node) => {
        const key = node.getAttribute('data-help-i18n-alt');
        const value = getValueByPath(locale, key);
        if (value !== undefined) {
            node.setAttribute('alt', value);
        }
    });

    const pageTitle = getValueByPath(locale, 'meta.title');
    if (pageTitle) {
        document.title = pageTitle;
    }
}

function applyMainLinksLanguage(language) {
    document.querySelectorAll('[data-help-link-main]').forEach((link) => {
        const baseHref = String(link.getAttribute('href') || link.getAttribute('data-help-main-href') || '/main');
        if (!baseHref.startsWith('/')) {
            return;
        }
        const url = new URL(baseHref, window.location.origin);
        url.searchParams.set('lang', language);
        if (link instanceof HTMLButtonElement) {
            link.dataset.helpMainHref = `${url.pathname}${url.search}`;
            link.addEventListener('click', () => {
                window.location.assign(link.dataset.helpMainHref || `${url.pathname}${url.search}`);
            });
            return;
        }
        link.setAttribute('href', `${url.pathname}${url.search}`);
    });
}

function markHelpReady() {
    document.body.classList.remove('is-loading');
    document.body.classList.add('is-ready');
    document.documentElement.classList.remove('lang-loading');
    document.documentElement.classList.add('lang-ready');
}

document.addEventListener('DOMContentLoaded', () => {
    const preferredLanguage = getPreferredLanguage();
    document.documentElement.lang = preferredLanguage;
    localStorage.setItem('preferredLanguage', preferredLanguage);
    applyHelpLocale(preferredLanguage);
    applyMainLinksLanguage(preferredLanguage);
    markHelpReady();

    const faqItems = document.querySelectorAll('.help-faq-item');
    faqItems.forEach((item) => {
        const button = item.querySelector('.help-faq-question');
        const answer = item.querySelector('.help-faq-answer');
        if (!button || !answer) {
            return;
        }

        const setOpen = (value) => {
            item.classList.toggle('is-open', value);
            answer.style.maxHeight = value ? `${answer.scrollHeight}px` : '0px';
        };

        setOpen(false);

        button.addEventListener('click', () => {
            const isOpen = item.classList.contains('is-open');
            faqItems.forEach((otherItem) => {
                const otherAnswer = otherItem.querySelector('.help-faq-answer');
                if (!otherAnswer) return;
                otherItem.classList.remove('is-open');
                otherAnswer.style.maxHeight = '0px';
            });
            setOpen(!isOpen);
        });
    });
});
